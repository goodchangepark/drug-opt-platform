LEVEL_LABELS = {
    1: "Base / Mechanistic Estimate",
    2: "Validated Base",
    3: "Validated Multi-Model",
    4: "Production Validated",
    5: "Mature Production Model",
}

STAR_SYMBOLS = {
    1: "★☆☆☆☆",
    2: "★★☆☆☆",
    3: "★★★☆☆",
    4: "★★★★☆",
    5: "★★★★★",
}


@dataclass(frozen=True)
class Maturity:
    level: int
    label: str
    stars: str
    active: bool
    reason: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "level": self.level,
            "label": self.label,
            "stars": self.stars,
            "active": self.active,
            "reason": self.reason,
            "aria_label": f"Prediction maturity {self.level} of 5 — {self.label}",
            "help": "Stars indicate the scientific validation and maturity tier of the model, not an absolute guarantee of accuracy.",
        }


def maturity_for_adapter(
    *,
    status: str,
    effective_n: float,
    activation_decision: str,
    stable_history_count: int = 0,
    representative_series: bool = False,
    compatible_evidence_only: bool = True,
) -> Maturity:
    """Project-specific adapter maturity (backward compatibility)."""
    active = activation_decision == "ACTIVATED" and compatible_evidence_only
    level = 1
    if active and effective_n >= 5 and status in {
        "LIGHT_PROJECT_ADAPTATION",
        "CANDIDATE_VALIDATED_IMPROVEMENT",
        "CANDIDATE_VALIDATED_NONDEGRADATION",
    }:
        level = 2
    if active and effective_n >= 10 and status == "REGULARIZED_PROJECT_ENSEMBLE":
        level = 3
    if active and effective_n >= 20 and status == "LOCAL_SERIES_ADAPTATION" and representative_series:
        level = 4
    if level == 4 and effective_n >= 40 and representative_series and stable_history_count >= 3:
        level = 5
    return Maturity(
        level=level,
        label=LEVEL_LABELS.get(level, "Base Prediction"),
        stars=STAR_SYMBOLS.get(level, "★☆☆☆☆"),
        active=level >= 2,
        reason=f"Project adapter status: {status}, effective N={effective_n:.1f}",
    )


