"""
Prediction Maturity System (5-Level Taxonomy) for Drug-OPT v3.3.1.
===================================================================

Authoritative endpoint-level maturity architecture:
  Level 1 (BASE / MECHANISTIC ESTIMATE / MODEL UNAVAILABLE):
    - Rule-based, physical chemistry equations, empirical descriptors (MW, cLogP, TPSA, etc.)
    - Mechanistic pharmacokinetic estimates (Oral CL/F, IV CL, Vd, etc. derived from HLM IVIVE)
    - Fail-closed model unavailable endpoints (CYP2C19 quantitative, P-gp quantitative, etc.)
  Level 2 (VALIDATED BASE):
    - Validated single quantitative base models or binary classifiers (TDC classifiers, Ames, DILI)
  Level 3 (VALIDATED MULTI-MODEL):
    - Validated multi-model consensus / candidate models (RLM Clint, MLM Clint, Vdss)
  Level 4 (PRODUCTION VALIDATED):
    - Independent locked holdout improvement, production promoted (v3.3.1 promoted endpoints)
    - Solubility, Caco-2, PPB, CYP3A4, CYP2D6, HLM, CYP1A2, CYP2C9, hERG
  Level 5 (MATURE):
    - Repeated independent cohorts, multi-series stable, real-world verified
"""
