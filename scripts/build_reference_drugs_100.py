def build_reference_100():
    with open(REF_80_PATH, "r") as f:
        drugs_80 = json.load(f)

    print(f"Loaded {len(drugs_80)} existing reference drugs from {REF_80_PATH.name}")

    existing_names = {d["name"].lower() for d in drugs_80}
    existing_db_ids = {d["drugbank_id"] for d in drugs_80}
    existing_cas = {d["cas_number"] for d in drugs_80 if d.get("cas_number")}

    print(f"Checking {len(NEW_20_DRUGS)} new candidate drugs...")
    validated_new_drugs = []

    for i, drug in enumerate(NEW_20_DRUGS, 1):
        name = drug["name"]
        db_id = drug["drugbank_id"]
        cas = drug["cas_number"]
        smiles = drug["smiles"]

        # Validate no duplicate
        assert name.lower() not in existing_names, f"Duplicate drug name: {name}"
        assert db_id not in existing_db_ids, f"Duplicate DrugBank ID: {db_id}"
        assert cas not in existing_cas, f"Duplicate CAS number: {cas}"

        # Validate RDKit parse
        mol = Chem.MolFromSmiles(smiles)
        assert mol is not None, f"Invalid SMILES for {name}: {smiles}"
        canon_smiles = Chem.MolToSmiles(mol, canonical=True)
        inchikey = Chem.MolToInchiKey(mol)

        # Re-set canonical SMILES
        drug["smiles"] = canon_smiles
        drug["inchikey"] = inchikey
        mw = float(Descriptors.MolWt(mol))
        clogp = float(Crippen.MolLogP(mol))
        drug["molecular_weight"] = round(mw, 2)
        drug["clogp"] = round(clogp, 2)

        print(f"  [{i:02d}/20] {name:15s} | DB: {db_id} | CAS: {cas:12s} | MW: {mw:6.1f} | Obs: {len(drug['observations'])}")
        validated_new_drugs.append(drug)

    full_catalog = drugs_80 + validated_new_drugs
    assert len(full_catalog) == 100, f"Expected 100 drugs, got {len(full_catalog)}"

    with open(REF_100_PATH, "w") as f:
        json.dump(full_catalog, f, indent=2)

    print(f"\nSuccessfully generated {REF_100_PATH.name} with {len(full_catalog)} approved reference drugs!")


if __name__ == "__main__":
    build_reference_100()
